function detectInitialLang() {
  try {
    const stored = localStorage.getItem(LANG_STORAGE_KEY);
    if (stored && SUPPORTED_LANGS.includes(stored)) return stored;
  } catch {
    // localStorage indisponible (navigation privée stricte, etc.)
  }
  const browserLang = (navigator.language || 'fr').slice(0, 2).toLowerCase();
  return SUPPORTED_LANGS.includes(browserLang) ? browserLang : 'fr';
}

let currentLang = detectInitialLang();

function getLang() {
  return currentLang;
}

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang) || lang === currentLang) return;
  currentLang = lang;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // tant pis, le choix ne survivra pas à un rechargement
  }
  document.documentElement.setAttribute('lang', lang);
  window.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
}

// Remplace {{clé}} dans une chaîne par les valeurs de `vars`.
function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{\{(\w+)\}\}/g, (match, key) => (key in vars ? vars[key] : match));
}

function t(key, vars) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.fr;
  const raw = dict[key] ?? TRANSLATIONS.fr[key] ?? key;
  return interpolate(raw, vars);
}

function applyStaticI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
}

const LANG_LABELS = { fr: 'FR', en: 'EN', de: 'DE', es: 'ES' };

function injectLanguageSwitcher() {
  document.querySelectorAll('#lang-switcher-slot').forEach((slot) => {
    const select = document.createElement('select');
    select.setAttribute('aria-label', 'Language / Langue');
    select.className = 'bg-transparent border border-current/30 rounded text-xs px-1.5 py-0.5 focus:outline-none cursor-pointer';
    select.innerHTML = SUPPORTED_LANGS.map((l) => `<option value="${l}">${LANG_LABELS[l]}</option>`).join('');
    select.value = currentLang;
    select.addEventListener('change', () => setLang(select.value));
    slot.replaceChildren(select);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  document.documentElement.setAttribute('lang', currentLang);
  injectLanguageSwitcher();
  applyStaticI18n();
});

window.addEventListener('i18n:change', () => {
  injectLanguageSwitcher();
  applyStaticI18n();
});
